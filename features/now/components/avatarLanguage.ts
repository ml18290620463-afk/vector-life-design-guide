export function useAvatarLanguage() {
  const language: 'zh' | 'en' = useAppStore((state) => state.language) === 'zh' ? 'zh' : 'en';
  const t = useCallback(
    (zh: string, en?: string) => (language === 'en' ? (en ?? EN[zh] ?? zh) : zh),
    [language],
  );
  return { language, t };
}
